            ) `
            -FromNodeId $technologyNodeId `
            -ToNodeId "technology:$($technology.RequiredTechnologyId)" `
            -RelationKind 'requires' `
            -Attributes ([ordered]@{}) `
            -SourceRef "exact-build:world.v1.json:technology:$($technology.Id)"
    }
}

