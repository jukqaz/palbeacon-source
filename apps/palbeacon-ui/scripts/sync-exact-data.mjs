const ensureInside = (root, candidate) => {
  const path = relative(root, candidate);
  if (path === '' || (!path.startsWith(`..${sep}`) && path !== '..')) return;
  throw new Error(`Refusing to operate outside ${root}: ${candidate}`);
};

const pathExists = async (path) => {
  try {
    await access(path);
    return true;
  } catch {
    return false;
  }
};

const recreateGeneratedDirectory = async (root) => {
  ensureInside(appRoot, root);
  if (await pathExists(root)) {
    const markerPath = resolve(root, generatedMarker);
    if (!(await pathExists(markerPath))) {
      throw new Error(`Refusing to replace unowned directory: ${root}`);
    }
    await rm(root, { recursive: true, force: true });
  }
  await mkdir(root, { recursive: true });
  await writeFile(resolve(root, generatedMarker), 'Generated by sync-exact-data.mjs\n');
};

const readJson = async (path) => JSON.parse(await readFile(path, 'utf8'));
const normalizeBuildId = (value) => String(value).replace(/^steam:/, '');

const sha256 = async (path) =>
  createHash('sha256')
    .update(await readFile(path))
    .digest('hex');

