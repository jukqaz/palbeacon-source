const itemRecordsById = new Map(catalogRecords.items.map((item) => [item.id, item]));
const palDropsByPalId = new Map();
for (const [itemId, drops] of dropsByItemId) {
  const item = itemRecordsById.get(itemId);
  if (!item) continue;
  for (const drop of drops) {
    const variants = palDropsByPalId.get(drop.pal_id) ?? new Map();
    const key = `${itemId}\u0000${drop.variant}`;
    const current = variants.get(key);
    if (
      current &&
      (current.probability_ppm > drop.probability_ppm ||
        (current.probability_ppm === drop.probability_ppm &&
          current.maximum_quantity >= drop.maximum_quantity))
    ) {
      continue;
    }
    variants.set(key, {
      item_id: itemId,
      name_ko: item.name_ko,
      image_path: item.image_path,
      rarity: item.rarity,
      variant: drop.variant,
      minimum_quantity: drop.minimum_quantity,
      maximum_quantity: drop.maximum_quantity,
      probability_ppm: drop.probability_ppm,
    });
    palDropsByPalId.set(drop.pal_id, variants);
  }
}
for (const pal of catalogRecords.pals) {
  pal.pal_drops = [...(palDropsByPalId.get(pal.id)?.values() ?? [])].toSorted(
    (left, right) =>
      Number(left.variant === 'boss') - Number(right.variant === 'boss') ||
      right.probability_ppm - left.probability_ppm ||
      left.name_ko.localeCompare(right.name_ko, 'ko') ||
      left.item_id.localeCompare(right.item_id),
  );
}

