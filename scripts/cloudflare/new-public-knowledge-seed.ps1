foreach ($recipe in $recipeModels) {
    $recipeNodeId = "recipe:$($recipe.Id)"
    Add-GraphEdge `
        -EdgeId "recipe-output:$($recipe.Id)" `
        -FromNodeId $recipeNodeId `
        -ToNodeId "item:$($recipe.OutputId)" `
        -RelationKind 'produces_item' `
        -Attributes ([ordered]@{ quantity = $recipe.OutputQuantity }) `
        -SourceRef "exact-build:items.v1.json:recipe:$($recipe.Id)"
    for ($index = 0; $index -lt $recipe.Ingredients.Count; $index++) {
        $ingredient = $recipe.Ingredients[$index]
        Add-GraphEdge `
            -EdgeId "recipe-ingredient:$($recipe.Id):$index" `
            -FromNodeId "item:$($ingredient.ItemId)" `
            -ToNodeId $recipeNodeId `
            -RelationKind 'ingredient_for' `
            -Attributes ([ordered]@{ quantity = $ingredient.Quantity }) `
            -SourceRef "exact-build:items.v1.json:recipe:$($recipe.Id)"
    }
}
foreach ($technology in $technologyModels) {
    $technologyNodeId = "technology:$($technology.Id)"
    foreach ($itemId in $technology.UnlockItemIds) {
