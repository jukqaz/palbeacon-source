const normalizeGameText = (value, effects = []) => {
  if (typeof value !== 'string' || value.trim().length === 0) return null;
  let output = value
    .replaceAll(/<characterName id=\|([^|]+)\|\/>/g, (_, id) => displayName(palsById.get(id), id))
    .replaceAll(/<activeSkillName id=\|([^|]+)\|\/>/g, (_, id) => activeSkillName(id))
    .replaceAll(/<uiCommon id=\|([^|]+)\|\/>/g, '$1')
    .replaceAll(/<[^>]+>/g, '')
    .replaceAll('\r\n', '\n');
  effects.forEach((effect, index) => {
    output = output.replaceAll(`{EffectValue${(index + 1).toString()}}`, String(effect.value));
  });
  output = output.replaceAll(/[+-]?\{EffectValue\d+\}%?/g, '(정확 수치 미확인)');
  output = output.replaceAll(/([+-]?\d+)\.0+(?=%)/g, '$1');
  return output.trim();
};

