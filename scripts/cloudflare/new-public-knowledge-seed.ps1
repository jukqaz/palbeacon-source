$relationEdgeCount = 0
foreach ($recipe in $recipeModels) {
    $relationEdgeCount += 1 + $recipe.Ingredients.Count
}
foreach ($technology in $technologyModels) {
    $relationEdgeCount += $technology.UnlockItemIds.Count
    $relationEdgeCount += $technology.UnlockRecipeIds.Count
    if (
        -not [string]::IsNullOrWhiteSpace($technology.RequiredTechnologyId) -and
        $technologyById.ContainsKey($technology.RequiredTechnologyId)
    ) {
        $relationEdgeCount++
    }
}
$pageCount = (
    $itemModels.Count + $recipeModels.Count + $technologyModels.Count
