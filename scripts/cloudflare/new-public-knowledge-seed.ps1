function ConvertTo-SqlText {
    param([AllowEmptyString()][string]$Value)

    $escaped = $Value.Replace("'", "''")
    return "'$escaped'"
}

function ConvertTo-CompactJson {
    param([Parameter(Mandatory)][AllowEmptyCollection()][object]$Value)

    return ConvertTo-Json -InputObject $Value -Depth 30 -Compress
}

function Get-TextSha256 {
    param([Parameter(Mandatory)][AllowEmptyString()][string]$Value)

    $sha = [Security.Cryptography.SHA256]::Create()
    try {
        $bytes = [Text.Encoding]::UTF8.GetBytes($Value)
        return (
            [BitConverter]::ToString($sha.ComputeHash($bytes)).
                Replace('-', '').
                ToLowerInvariant()
        )
    }
    finally {
        $sha.Dispose()
    }
}

function Get-FileSha256 {
    param([Parameter(Mandatory)][string]$Path)

    return (Get-FileHash -Algorithm SHA256 -LiteralPath $Path).
        Hash.ToLowerInvariant()
}

function Assert-InternalId {
    param(
        [Parameter(Mandatory)][string]$Value,
        [Parameter(Mandatory)][string]$Kind
    )

    if (
        $Value.Length -gt 220 -or
        $Value -notmatch '^[A-Za-z0-9_.:-]+$'
    ) {
        throw "$Kind contains an unsupported internal identifier: $Value"
    }
}

function Write-Utf8File {
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][AllowEmptyString()][string]$Content
    )

    [IO.File]::WriteAllText($Path, $Content, $utf8NoBom)
}

function New-SqlDocument {
    param([Parameter(Mandatory)][string[]]$Statements)

    return (
        "-- Generated by $compilerVersion. Do not edit.`n" +
        "PRAGMA foreign_keys=ON;`n" +
        ($Statements -join "`n") +
        "`n"
    )
}

function Write-SqlChunks {
    param(
        [Parameter(Mandatory)][string]$Prefix,
        [Parameter(Mandatory)][AllowEmptyCollection()]
        [Collections.Generic.List[string]]$Statements,
        [Parameter(Mandatory)][ValidateRange(1, 100)]
        [int]$BaseRowsPerStatement
    )

    $paths = New-Object Collections.Generic.List[string]
    for ($offset = 0; $offset -lt $Statements.Count; $offset += $ChunkSize) {
        $last = [Math]::Min($offset + $ChunkSize - 1, $Statements.Count - 1)
        $chunk = @($Statements[$offset..$last])
        $index = [int]($offset / $ChunkSize)
        $name = '{0}_{1:D4}.sql' -f $Prefix, $index
        Write-SeedSqlFile `
            -Name $name `
            -Statements $chunk `
            -BaseRowsWrittenUpperBound (
                $chunk.Count * $BaseRowsPerStatement
            )
        $paths.Add($name)
    }
    return @($paths | ForEach-Object { $_ })
}

function Write-SeedSqlFile {
    param(
        [Parameter(Mandatory)][string]$Name,
        [Parameter(Mandatory)][string[]]$Statements,
        [Parameter(Mandatory)][ValidateRange(0, [long]::MaxValue)]
        [long]$BaseRowsWrittenUpperBound
    )

    $applyOrder = $writtenSql.Count
    $payloadDocument = New-SqlDocument $Statements
    $payloadSha256 = Get-TextSha256 $payloadDocument
    # The checkpoint row and its dataset/time index add two more D1 writes.
    $baseRowsWithCheckpoint = $BaseRowsWrittenUpperBound + 2
    $conservativeRowsWritten = [long][Math]::Ceiling(
        $baseRowsWithCheckpoint * 3.0
    )
    $checkpointInput = ConvertTo-CompactJson ([ordered]@{
        path = $Name
        payload_sha256 = $payloadSha256
        apply_order = $applyOrder
    })
    $checkpointOutput = ConvertTo-CompactJson ([ordered]@{
        base_rows_written_upper_bound = $baseRowsWithCheckpoint
        conservative_rows_written = $conservativeRowsWritten
    })
    $checkpointRunId = (
        "seed-checkpoint:${DatasetVersion}:{0:D4}" -f $applyOrder
    )
    $checkpointStatement = (
        "INSERT INTO knowledge_pipeline_runs " +
        "(run_id, dataset_version, pipeline_name, compiler_version, status, " +
        "input_facets_json, output_facets_json, completed_at) VALUES (" +
        "$(ConvertTo-SqlText $checkpointRunId), " +
        "$(ConvertTo-SqlText $DatasetVersion), " +
        "'public-metadata-seed-checkpoint-v1', " +
        "$(ConvertTo-SqlText $compilerVersion), 'completed', " +
        "$(ConvertTo-SqlText $checkpointInput), " +
        "$(ConvertTo-SqlText $checkpointOutput), CURRENT_TIMESTAMP);"
    )
    $path = Join-Path $resolvedOutput $Name
    Write-Utf8File `
        -Path $path `
        -Content (New-SqlDocument @($Statements + $checkpointStatement))
    $writtenSql.Add($Name)
    $sqlFileRecords.Add([pscustomobject][ordered]@{
        path = $Name
        payload_sha256 = $payloadSha256
        base_rows_written_upper_bound = $baseRowsWithCheckpoint
        conservative_rows_written = $conservativeRowsWritten
        apply_order = $applyOrder
    })
}

$resolvedItems = [IO.Path]::GetFullPath($ItemsCatalog)
$resolvedWorld = [IO.Path]::GetFullPath($WorldCatalog)
$resolvedOutput = [IO.Path]::GetFullPath($OutputDirectory)

foreach ($catalogPath in @($resolvedItems, $resolvedWorld)) {
    if (-not (Test-Path -LiteralPath $catalogPath -PathType Leaf)) {
        throw "Required exact-Build catalog does not exist: $catalogPath"
    }
}
if (Test-Path -LiteralPath $resolvedOutput) {
    throw "Output directory already exists; refusing to overwrite: $resolvedOutput"
}
if ($DatasetVersion -notmatch '^[A-Za-z0-9_.:-]+$') {
    throw 'DatasetVersion must be an ASCII internal identifier.'
}

$itemsDocument = Get-Content -Raw -Encoding UTF8 -LiteralPath $resolvedItems |
    ConvertFrom-Json
$worldDocument = Get-Content -Raw -Encoding UTF8 -LiteralPath $resolvedWorld |
    ConvertFrom-Json
foreach ($document in @($itemsDocument, $worldDocument)) {
    if ($document.verified -ne $true) {
        throw 'Public metadata may be compiled only from a verified catalog.'
    }
    if ([string]$document.game_build_id -ne $GameBuildId) {
        throw (
            "Catalog game_build_id '$($document.game_build_id)' does not " +
            "match requested '$GameBuildId'."
        )
    }
}
if (
    [string]$itemsDocument.mapping_sha256 -ne
    [string]$worldDocument.mapping_sha256
) {
    throw 'Item and world catalogs do not share the same mapping SHA-256.'
}

$itemModels = New-Object Collections.Generic.List[object]
$itemById = New-Object (
    'Collections.Generic.Dictionary[string,object]'
) ([StringComparer]::Ordinal)
foreach (
    $item in @(
        $itemsDocument.items |
            Sort-Object { [string]$_.item_id }
    )
) {
    if (
        $item.legal_in_game -ne $true -or
        $item.localization_fallback -eq $true -or
        [string]::IsNullOrWhiteSpace([string]$item.name_ko)
    ) {
        continue
    }
    $id = [string]$item.item_id
    Assert-InternalId -Value $id -Kind 'Item'
    if ($itemById.ContainsKey($id)) {
        throw "Duplicate item identifier: $id"
    }
    $model = [pscustomobject][ordered]@{
        Id = $id
        Name = ([string]$item.name_ko).Trim()
        Rarity = [int64]$item.rarity
        Rank = [int64]$item.rank
        Stack = [int64]$item.maximum_stack_count
        WeightMilli = [int64]$item.weight_milli
    }
    $itemModels.Add($model)
    $itemById.Add($id, $model)
}

# Exact game localization intentionally gives rarity variants the same visible
# name. Add a Korean, numeric rarity suffix only when that name is ambiguous so
# the public Wiki never renders indistinguishable cards or relation chips.
foreach (
    $duplicateNameGroup in @(
        $itemModels |
            Group-Object Name |
            Where-Object { $_.Count -gt 1 }
    )
) {
    foreach ($item in $duplicateNameGroup.Group) {
        $item.Name = "$($item.Name) · 희귀도 $($item.Rarity)"
    }
}

$recipeModels = New-Object Collections.Generic.List[object]
$recipeById = New-Object (
    'Collections.Generic.Dictionary[string,object]'
) ([StringComparer]::Ordinal)
foreach (
    $recipe in @(
        $itemsDocument.recipes |
            Sort-Object { [string]$_.recipe_id }
    )
) {
    $recipeId = [string]$recipe.recipe_id
    $outputId = [string]$recipe.output_item_id
    if (-not $itemById.ContainsKey($outputId)) {
        continue
    }
    Assert-InternalId -Value $recipeId -Kind 'Recipe'
    if ($recipeById.ContainsKey($recipeId)) {
        throw "Duplicate recipe identifier: $recipeId"
    }
    $ingredients = New-Object Collections.Generic.List[object]
    $complete = $true
    foreach ($ingredient in @($recipe.ingredients)) {
        $ingredientId = [string]$ingredient.item_id
        if (-not $itemById.ContainsKey($ingredientId)) {
            $complete = $false
            break
        }
        $ingredients.Add([pscustomobject][ordered]@{
            ItemId = $ingredientId
            Name = $itemById[$ingredientId].Name
            Quantity = [int64]$ingredient.quantity
        })
    }
    if (-not $complete -or $ingredients.Count -eq 0) {
        continue
    }
    $output = $itemById[$outputId]
    $model = [pscustomobject][ordered]@{
        Id = $recipeId
        Name = "$($output.Name) 제작법"
        OutputId = $outputId
        OutputName = $output.Name
        OutputQuantity = [int64]$recipe.output_quantity
        WorkAmount = [int64]$recipe.work_amount
        Ingredients = @($ingredients | ForEach-Object { $_ })
    }
    $recipeModels.Add($model)
    $recipeById.Add($recipeId, $model)
}

$technologyModels = New-Object Collections.Generic.List[object]
$technologyById = New-Object (
    'Collections.Generic.Dictionary[string,object]'
) ([StringComparer]::Ordinal)
foreach (
    $technology in @(
        $worldDocument.technologies |
            Sort-Object { [string]$_.technology_id }
    )
) {
    if (
        $technology.localization_fallback -eq $true -or
        [string]::IsNullOrWhiteSpace([string]$technology.name_ko)
    ) {
        continue
    }
    $id = [string]$technology.technology_id
    Assert-InternalId -Value $id -Kind 'Technology'
    if ($technologyById.ContainsKey($id)) {
        throw "Duplicate technology identifier: $id"
    }
    $unlockItems = @(
        @($technology.unlock_item_ids) |
            ForEach-Object { [string]$_ } |
            Where-Object { $itemById.ContainsKey($_) } |
            Sort-Object -Unique
    )
    $unlockRecipes = @(
        @($technology.unlock_recipe_ids) |
            ForEach-Object { [string]$_ } |
            Where-Object { $recipeById.ContainsKey($_) } |
            Sort-Object -Unique
    )
    $model = [pscustomobject][ordered]@{
        Id = $id
        Name = ([string]$technology.name_ko).Trim()
        Level = [int64]$technology.level
        Cost = [int64]$technology.cost
        IsBoss = [bool]$technology.is_boss_technology
        RequiredTechnologyId = [string]$technology.required_technology_id
        UnlockItemIds = $unlockItems
        UnlockRecipeIds = $unlockRecipes
    }
    $technologyModels.Add($model)
    $technologyById.Add($id, $model)
}

