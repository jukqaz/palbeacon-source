function Add-GraphNode {
    param(
        [Parameter(Mandatory)][string]$NodeId,
        [Parameter(Mandatory)][string]$NodeKind,
        [Parameter(Mandatory)][string]$Label,
        [Parameter(Mandatory)][string]$SourceRef,
        [Parameter(Mandatory)][object]$HashInput
    )

    Assert-InternalId -Value $NodeId -Kind 'Graph node'
    if (-not $nodeIds.Add($NodeId)) {
        throw "Duplicate graph node: $NodeId"
    }
    $evidenceJson = ConvertTo-CompactJson @($SourceRef, $buildEvidence)
    $contentHash = Get-TextSha256 (ConvertTo-CompactJson $HashInput)
    $nodeStatements.Add(
        "INSERT INTO knowledge_graph_nodes " +
        "(dataset_version, node_id, node_kind, label_ko, evidence_quality, " +
        "evidence_refs_json, content_hash) VALUES (" +
        "$datasetSql, $(ConvertTo-SqlText $NodeId), " +
        "$(ConvertTo-SqlText $NodeKind), $(ConvertTo-SqlText $Label), " +
        "'exact', $(ConvertTo-SqlText $evidenceJson), " +
        "$(ConvertTo-SqlText $contentHash));"
    )
}

function Add-GraphEdge {
    param(
        [Parameter(Mandatory)][string]$EdgeId,
        [Parameter(Mandatory)][string]$FromNodeId,
        [Parameter(Mandatory)][string]$ToNodeId,
        [Parameter(Mandatory)][string]$RelationKind,
        [Parameter(Mandatory)][object]$Attributes,
        [Parameter(Mandatory)][string]$SourceRef
    )

    if (
        -not $nodeIds.Contains($FromNodeId) -or
        -not $nodeIds.Contains($ToNodeId)
    ) {
        throw "Graph edge $EdgeId references a missing endpoint."
    }
    $evidenceJson = ConvertTo-CompactJson @($SourceRef, $buildEvidence)
    $attributesJson = ConvertTo-CompactJson $Attributes
    $contentHash = Get-TextSha256 (
        ConvertTo-CompactJson ([ordered]@{
            edge_id = $EdgeId
            from = $FromNodeId
            to = $ToNodeId
            relation = $RelationKind
            attributes = $Attributes
        })
    )
    $edgeStatements.Add(
        "INSERT INTO knowledge_graph_edges " +
        "(dataset_version, edge_id, from_node_id, to_node_id, relation_kind, " +
        "origin, evidence_quality, evidence_refs_json, attributes_json, " +
        "content_hash) VALUES (" +
        "$datasetSql, $(ConvertTo-SqlText $EdgeId), " +
        "$(ConvertTo-SqlText $FromNodeId), $(ConvertTo-SqlText $ToNodeId), " +
        "$(ConvertTo-SqlText $RelationKind), 'exact_extract', 'exact', " +
        "$(ConvertTo-SqlText $evidenceJson), " +
        "$(ConvertTo-SqlText $attributesJson), " +
        "$(ConvertTo-SqlText $contentHash));"
    )
}

function Add-WikiPage {
    param(
        [Parameter(Mandatory)][string]$EntityNodeId,
        [Parameter(Mandatory)][string]$PageKind,
        [Parameter(Mandatory)][string]$Title,
        [Parameter(Mandatory)][string]$Summary,
        [Parameter(Mandatory)][string]$Body,
        [Parameter(Mandatory)][string]$Claim,
        [Parameter(Mandatory)][string]$SourceRef
    )

    $pageId = "wiki:$EntityNodeId"
    Assert-InternalId -Value $pageId -Kind 'Wiki page'
    if (-not $pageIds.Add($pageId)) {
        throw "Duplicate Wiki page: $pageId"
    }
    $relatedJson = ConvertTo-CompactJson @($EntityNodeId)
    $evidenceJson = ConvertTo-CompactJson @($SourceRef, $buildEvidence)
    $claimId = "claim:$EntityNodeId"
    $pageNodeId = "wiki-page:$EntityNodeId"

    Add-GraphNode `
        -NodeId $pageNodeId `
        -NodeKind 'wiki_page' `
        -Label $Title `
        -SourceRef "wiki-policy:$compilerVersion" `
        -HashInput ([ordered]@{
            page_id = $pageId
            title = $Title
            summary = $Summary
            body = $Body
        })
    Add-GraphEdge `
        -EdgeId "wiki-reference:$EntityNodeId" `
        -FromNodeId $pageNodeId `
        -ToNodeId $EntityNodeId `
        -RelationKind 'references' `
        -Attributes ([ordered]@{}) `
        -SourceRef "wiki-claim:$claimId"

    $pageStatements.Add(
        "INSERT INTO knowledge_wiki_pages " +
        "(dataset_version, page_id, page_kind, title_ko, summary_ko, " +
        "body_markdown, related_node_ids_json, source_manifest_sha256, " +
        "review_status) VALUES (" +
        "$datasetSql, $(ConvertTo-SqlText $pageId), " +
        "$(ConvertTo-SqlText $PageKind), $(ConvertTo-SqlText $Title), " +
        "$(ConvertTo-SqlText $Summary), $(ConvertTo-SqlText $Body), " +
        "$(ConvertTo-SqlText $relatedJson), $manifestSql, 'reviewed');"
    )
    $claimStatements.Add(
        "INSERT INTO knowledge_wiki_claims " +
        "(dataset_version, page_id, claim_id, claim_text_ko, " +
        "evidence_quality, evidence_refs_json, related_node_ids_json) VALUES (" +
        "$datasetSql, $(ConvertTo-SqlText $pageId), " +
        "$(ConvertTo-SqlText $claimId), $(ConvertTo-SqlText $Claim), " +
        "'exact', $(ConvertTo-SqlText $evidenceJson), " +
        "$(ConvertTo-SqlText $relatedJson));"
    )
    $claimsJson = ConvertTo-CompactJson @(
        [ordered]@{
            claim_id = $claimId
            text_ko = $Claim
            quality = 'exact'
            evidence_refs = @($SourceRef, $buildEvidence)
            related_node_ids = @($EntityNodeId)
        }
    )
    $revisionStatements.Add(
        "INSERT INTO knowledge_wiki_revisions " +
        "(dataset_version, page_id, revision_number, title_ko, summary_ko, " +
        "body_markdown, claims_json, related_node_ids_json, change_origin, " +
        "review_status, generator_id, reviewer_id, change_summary_ko) VALUES (" +
        "$datasetSql, $(ConvertTo-SqlText $pageId), 1, " +
        "$(ConvertTo-SqlText $Title), $(ConvertTo-SqlText $Summary), " +
        "$(ConvertTo-SqlText $Body), $(ConvertTo-SqlText $claimsJson), " +
        "$(ConvertTo-SqlText $relatedJson), 'exact_compiler', 'reviewed', " +
        "$(ConvertTo-SqlText $compilerVersion), 'public-metadata-policy-v1', " +
        "'공개 허용 구조 데이터로 최초 컴파일');"
    )
}

