            -Attributes ([ordered]@{
                level = $technology.Level
                cost = $technology.Cost
            }) `
            -SourceRef "exact-build:world.v1.json:technology:$($technology.Id)"
    }
    foreach ($recipeId in $technology.UnlockRecipeIds) {
        Add-GraphEdge `
            -EdgeId "technology-unlock-recipe:$($technology.Id):$recipeId" `
            -FromNodeId $technologyNodeId `
            -ToNodeId "recipe:$recipeId" `
            -RelationKind 'unlocks' `
            -Attributes ([ordered]@{
                level = $technology.Level
                cost = $technology.Cost
            }) `
            -SourceRef "exact-build:world.v1.json:technology:$($technology.Id)"
